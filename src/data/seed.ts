/** Deterministic UUID from a string, so seed ids are stable across runs. */
export function seedId(key: string): string {
  let h1 = 0x811c9dc5;
  let h2 = 0x12345678;
  let hex = '';
  for (let round = 0; hex.length < 32; round++) {
    for (let i = 0; i < key.length; i++) {
      h1 = Math.imul(h1 ^ key.charCodeAt(i), 16777619) >>> 0;
      h2 = Math.imul(h2 ^ (key.charCodeAt(i) + round), 2246822519) >>> 0;
    }
    hex += h1.toString(16).padStart(8, '0') + h2.toString(16).padStart(8, '0');
  }
  hex = hex.slice(0, 32);
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-4${hex.slice(13, 16)}-a${hex.slice(17, 20)}-${hex.slice(20, 32)}`;
}

const photo = (owner: string, name: string, sort: number, label: string | null = null): Photo => ({
  id: seedId(`${owner}:${name}`),
  path: `/photos/${name}.jpg`,
  label,
  credit: 'Unsplash',
  sort,
});

